CREATE TABLE users
(
    user_id                 INTEGER GENERATED BY DEFAULT AS IDENTITY,
    username                VARCHAR(255) NOT NULL,
    role                    INTEGER NOT NULL DEFAULT 0,
    display_name            VARCHAR(255) NOT NULL,
    active_directory_guid   UUID NULL,
    email                   VARCHAR(255) NOT NULL,
    password                VARCHAR(255) NOT NULL DEFAULT '',
    salt                    VARCHAR(255) NOT NULL DEFAULT '',
    account_type            INTEGER NOT NULL DEFAULT 1,
    is_active               BOOLEAN NOT NULL DEFAULT FALSE,
    two_factor_enabled      BOOLEAN NOT NULL,
    lockout_end             TIMESTAMPTZ NULL,
    lockout_enabled         BOOLEAN NOT NULL,
    access_failed_count     INTEGER NOT NULL DEFAULT 0,
    two_factor_token        TEXT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_username_account_type UNIQUE (username, account_type),
    CONSTRAINT uq_users_active_directory_guid UNIQUE (active_directory_guid)
);
